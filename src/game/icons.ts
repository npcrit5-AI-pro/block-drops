function materialOf(id: string) {
  const keys = ["netherite", "diamond", "golden", "chainmail", "copper", "iron", "stone", "wooden", "leather"];
  return keys.find((k) => id.startsWith(k)) ?? "";
}

export function familyOf(id: string) {
  if (/_pickaxe$/.test(id)) return "pick";
  if (/_shovel$/.test(id)) return "shovel";
  if (/_hoe$/.test(id)) return "hoe";
  if (/_sword$/.test(id)) return "sword";
  if (/_spear$/.test(id) || id === "trident") return "spear";
  if (/_axe$/.test(id)) return "axe";
  if (/helmet$/.test(id)) return "helm";
  if (/chestplate$/.test(id) || id === "elytra") return "chest";
  if (/leggings$/.test(id)) return "legs";
  if (/boots$/.test(id)) return "boots";
  if (id === "shield") return "shield";
  if (id.includes("map")) return "map";
  if (id.includes("compass")) return "compass";
  if (id === "clock") return "clock";
  if (id.includes("bucket")) return "bucket";
  if (id === "crossbow") return "crossbow";
  if (id === "bow") return "bow";
  if (id.includes("apple")) return "apple";
  if (/_ingot$|_nugget$/.test(id)) return "ingot";
  if (id.endsWith("spawn_egg")) return "egg";
  if (/potion_|splash_|lingering_|^potion/.test(id) || id.includes("bottle")) return "potion";
  if (id.startsWith("music_disc")) return "disc";
  if (/boat$|raft$/.test(id)) return "boat";
  if (id.endsWith("_door")) return "door";
  if (id === "mace") return "mace";
  if (/sapling$|tulip$|orchid$|daisy$|dandelion$|poppy$|allium$|bluet$|peony$|lilac$|rose_bush$|blossom$|torchflower$|sunflower$|cornflower$|lily/.test(id)) return "flower";
  return "";
}

