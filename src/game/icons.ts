const VARY = new Set(["block", "item", "food", "egg", "potion", "disc", "flower", "door", "boat", "apple"]);

function palette(item: DropItem, shape: string) {
  const mat = materialOf(item.id);
  const metal = MAT[mat];
  const tool = shape === "sword" || shape === "pick" || shape === "axe" || shape === "shovel" || shape === "hoe" || shape === "spear" || shape === "mace";
  const armor = shape === "helm" || shape === "chest" || shape === "legs" || shape === "boots";
  const useMetal = (tool || armor) && metal;
  const main = useMetal ? metal[0] : item.color;
  const light = useMetal ? metal[1] : shade(item.color, 1.28);
  const dark = useMetal ? metal[2] : shade(item.color, 0.58);
  const pal: Record<string, string> = {
    "1": main,
    "2": light,
    "3": dark,
    "4": mat === "netherite" ? "#3a241c" : "#6b4424",
    "5": mat === "netherite" ? "#1a100c" : "#3a2412",
    "6": item.color,
    "7": "#f3ecdf",
  };
  if (shape === "compass") pal["6"] = "#d02020";
  if (shape === "clock") {
    pal["1"] = "#f0c84a";
    pal["2"] = "#ffe98a";
    pal["3"] = "#2a2418";
  }
  if (shape === "shield") {
    pal["1"] = "#c6c6c6";
    pal["2"] = "#f4f4f4";
    pal["3"] = "#8a5a32";
  }
  if (shape === "map") pal["6"] = "#5d9a3c";
  if (shape === "flower") pal["6"] = item.color;
  if (shape === "apple") {
    pal["1"] = item.color;
    pal["2"] = shade(item.color, 1.2);
    pal["3"] = shade(item.color, 0.7);
    pal["6"] = "#3d7a32";
  }
  if (shape === "bucket" && item.id !== "bucket") {
    pal["1"] = item.color;
    pal["2"] = shade(item.color, 1.25);
    pal["3"] = shade(item.color, 0.7);
  }
  return pal;
}

const cache = new Map<string, string>();

export function iconFor(item: DropItem) {
  const hit = cache.get(item.id);
  if (hit) return hit;
  const shape = familyOf(item.id) || (item.kind === "block" ? "block" : item.group === "Food" ? "food" : "item");
  const mask = MASKS[shape] ?? GEM;
  const pal = palette(item, shape);
  const h = hash(item.id);
  const vary = VARY.has(shape);
  const pixels: (string | null)[][] = [];
  for (let y = 0; y < 16; y++) {
    const row = mask[y] ?? "0000000000000000";
    const line: (string | null)[] = [];
    for (let x = 0; x < 16; x++) {
      let ch = row[x] ?? "0";
      if (vary && ch === "1" && ((h >>> ((x * 3 + y) % 24)) & 3) === 1) ch = (h >>> (x % 8)) & 1 ? "2" : "3";
      if (ch === "0") line.push(null);
      else line.push(pal[ch] ?? FIXED[ch] ?? null);
    }
    pixels.push(line);
  }
  if (vary) {
    const mark = `#${(h & 0xffffff).toString(16).padStart(6, "0")}`;
    pixels[1 + ((h >>> 4) % 12)]![1 + (h % 12)] = mark;
    pixels[2 + ((h >>> 12) % 10)]![2 + ((h >>> 8) % 10)] = shade(mark, 0.72);
  }
  let rects = "";
  for (let y = 0; y < 16; y++) {
    for (let x = 0; x < 16; x++) {
      const fill = pixels[y]![x];
      if (!fill) continue;
      rects += `<rect x='${x}' y='${y}' width='1' height='1' fill='${fill}'/>`;
    }
  }
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 16' shape-rendering='crispEdges'>${rects}</svg>`;
  const url = `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
  cache.set(item.id, url);
  return url;
}

export function armorSlotOf(id: string) {
  if (/helmet$/.test(id)) return 0;
  if (/chestplate$/.test(id) || id === "elytra") return 1;
  if (/leggings$/.test(id)) return 2;
  if (/boots$/.test(id) && !id.includes("horse")) return 3;
  return -1;
}

const POINTS: Record<string, number[]> = {
  leather: [1, 3, 2, 1],
  copper: [1, 4, 3, 1],
  chainmail: [2, 5, 4, 1],
  iron: [2, 6, 5, 2],
  golden: [2, 5, 3, 1],
  diamond: [3, 8, 6, 3],
  netherite: [3, 8, 6, 3],
  turtle: [2, 0, 0, 0],
};

export function armorPoints(worn: (string | null)[]) {
  let n = 0;
  worn.forEach((id, i) => {
    if (!id) return;
    const mat = id.replace(/_(helmet|chestplate|leggings|boots)$/, "");
    n += POINTS[mat]?.[i] ?? 0;
  });
  return n;
}
